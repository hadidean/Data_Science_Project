"""# **MULTIPLE LINEAR REGRESSION**"""

from sklearn.linear_model import LinearRegression
import pandas as pd

# Create model
lr_model = LinearRegression()

# Handle NaNs in X_train and y_train before fitting
# Combine X_train and y_train to drop rows with NaNs consistently
train_data = pd.concat([X_train, y_train], axis=1)
train_data_cleaned = train_data.dropna()

X_train_cleaned = train_data_cleaned[X_train.columns]
y_train_cleaned = train_data_cleaned[y_train.name]

# Train model with cleaned data
lr_model.fit(X_train_cleaned, y_train_cleaned)

print("Linear Regression model trained successfully!")

# Predict using test data
y_pred_lr = lr_model.predict(X_test)

# Display predictions
print("Predicted Values:")
print(y_pred_lr[:5])

"""# **EVALUATE MULTIPLE LINEAR REGRESSION MODEL**"""

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)
import numpy as np

# MAE
mae_lr = mean_absolute_error(y_test, y_pred_lr)

# MSE (mean_squared_error computes MSE by default)
mse_lr = mean_squared_error(y_test, y_pred_lr)
# RMSE (take the square root of MSE)
rmse_lr = np.sqrt(mse_lr)

# R² Score
r2_lr = r2_score(y_test, y_pred_lr)

# Display Results
